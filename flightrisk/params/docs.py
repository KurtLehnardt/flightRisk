"""Render ``docs/flight-parameters.md`` from the registry.

The text is generated: a test fails when the committed file differs from
``render_flight_parameters_markdown()``. Test-adapter facts (rows whose edit
mode is ``Edit.FACT``) appear only in a read-only table that gives the value
and its source. They never appear among the settings, no environment name is
printed for them, and the text around them never invites a change (risk R6).
"""

from __future__ import annotations

from typing import Any

from flightrisk.hardware.catalogue import BUILTIN_MODELS

from .spec import Bound, Edit, ParamSpec
from .table import FACT_NOTE, TABLE

# The parameter profiles in catalogue order, each listed once.
PROFILES = tuple(dict.fromkeys(m.profile for m in BUILTIN_MODELS.values()))

# A profile heading is the coverage name of its first built-in model in catalogue order. An entry here overrides that
# name only where the heading is deliberately shorter than the coverage name.
_PROFILE_NAMES = {"generic_multirotor": "Generic"}


def _profile_name(profile: str) -> str:
    """The display name used in the column headings for one profile.

    It is the override in ``_PROFILE_NAMES`` when there is one, and otherwise the coverage name of the first built-in
    model of that profile in catalogue order.
    """
    if profile in _PROFILE_NAMES:
        return _PROFILE_NAMES[profile]
    return next(m.coverage_name or m.name for m in BUILTIN_MODELS.values() if m.profile == profile)


_EDIT_WORDS = {
    Edit.UI: "setting",
    Edit.FILE_ENV: "file or environment",
    Edit.READ_ONLY: "read-only",
    Edit.FACT: "read-only",
}


def is_fact_row(row: ParamSpec) -> bool:
    """True when the row is a test-adapter fact on any profile."""
    return any(e is Edit.FACT for e in row.edit.values())


def is_read_only_row(row: ParamSpec) -> bool:
    """True when no profile can change the row and it is not a fact."""
    return not is_fact_row(row) and all(e is Edit.READ_ONLY for e in row.edit.values())


def _value(value: Any) -> str:
    """One value as plain text."""
    if value is None:
        return "not applicable"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    if isinstance(value, str) and ":" in value:
        kind, _, rest = value.partition(":")
        return f"{kind} ({rest.replace('_', ' ')})"
    return str(value)


def _bound(bound: Bound | None) -> str:
    if bound is None:
        return "none"
    if bound.lo == bound.hi:
        return f"fixed at {_value(bound.lo)}"
    return f"{_value(bound.lo)} to {_value(bound.hi)}"


def _cell(text: str) -> str:
    return text.replace("|", "/").replace("\n", " ")


def _settings_table(rows: list[ParamSpec]) -> list[str]:
    heads = [h for p in PROFILES for h in (f"{_profile_name(p)} default", f"{_profile_name(p)} bound")]
    columns = ["Id", "Description", "Unit", *heads, "Edit"]
    out = ["| " + " | ".join(columns) + " |", "| " + " | ".join("---" for _ in columns) + " |"]
    for r in rows:
        edit = " / ".join(sorted({_EDIT_WORDS[r.edit[p]] for p in PROFILES}))
        cells = [f"`{r.id}`", _cell(r.description), r.unit.value]
        for p in PROFILES:
            cells += [_value(r.defaults.get(p)), _bound(r.bounds.get(p))]
        out.append("| " + " | ".join(cells + [edit]) + " |")
    return out


def _fact_table(rows: list[ParamSpec]) -> list[str]:
    out = ["| Id | Meaning | Unit | Tello value | Source |", "| --- | --- | --- | --- | --- |"]
    for r in rows:
        meaning = r.description.replace(FACT_NOTE, "").strip()
        out.append(f"| `{r.id}` | {_cell(meaning)} | {r.unit.value} | {_value(r.defaults.get('tello'))} | Tello test adapter |")
    return out


def render_flight_parameters_markdown() -> str:
    """Render the registry as the text of ``docs/flight-parameters.md``."""
    settings = [r for r in TABLE if not is_fact_row(r) and not is_read_only_row(r)]
    read_only = [r for r in TABLE if is_read_only_row(r)]
    facts = [r for r in TABLE if is_fact_row(r)]
    out = [
        "# Flight parameters",
        "",
        "Generated by `flightrisk.params.docs.render_flight_parameters_markdown()`. Do not edit by hand.",
        "",
        "Distances are in centimetres and times in seconds, unless the unit column says otherwise. "
        "A default of `not applicable` means the row does not apply to that model.",
        "",
        f"The registry holds {len(TABLE)} rows: {len(settings)} settings, {len(read_only)} read-only values "
        f"and {len(facts)} test-adapter facts.",
    ]
    for heading, subset in (("Settings", settings), ("Read-only values", read_only)):
        groups: dict[str, list[ParamSpec]] = {}
        for r in subset:
            groups.setdefault(r.group, []).append(r)
        for group, rows in groups.items():
            out += ["", f"## {heading}: {group}", ""] + _settings_table(rows)
    out += [
        "",
        "## Test-adapter facts (read-only)",
        "",
        "These values are read-only. They describe what the test adapter does today and are listed so "
        "that readers know them. They are not settings.",
        "",
    ] + _fact_table(facts)
    return "\n".join(out) + "\n"
