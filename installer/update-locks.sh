#!/usr/bin/env bash
# Regenerate the pinned dependency lists the installers install from.
#
#   bash installer/update-locks.sh [path/to/a/working/venv/bin/python]
#
# Each lock is resolved by uv (https://docs.astral.sh/uv/) for one platform and
# Python 3.13, with the packages of a working virtual environment as
# constraints, so the pins are the versions that environment already runs and
# tests with. Without an argument the repository's own venv is used. Only
# wheels are allowed (no package is built from source at install time), and
# every file carries its SHA-256, so the installers can run pip with
# --require-hashes --only-binary :all:.
#
#   installer/locks/macos-arm64.txt        requirements.txt, macOS 14 or newer on Apple Silicon
#   installer/locks/windows-x64-edge.txt   requirements-edge.txt, 64-bit Windows (the edge laptop)
#
# Commit the result together with the change to requirements*.txt that needed it.
set -euo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
PYTHON="${1:-$ROOT/venv/bin/python}"
command -v uv >/dev/null 2>&1 || { echo "update-locks.sh: uv is needed (brew install uv)" >&2; exit 1; }
[ -x "$PYTHON" ] || { echo "update-locks.sh: $PYTHON is not an executable Python" >&2; exit 1; }

work="$(mktemp -d "${TMPDIR:-/tmp}/flightrisk-locks.XXXXXX")"
trap 'rm -rf -- "$work"' EXIT
uv pip freeze --python "$PYTHON" > "$work/constraints.txt"

compile() {
  local requirements="$1" platform="$2" out="$3" title="$4"
  {
    printf '# %s\n' "$title"
    printf '# Generated by installer/update-locks.sh from %s; do not edit by hand.\n' "$requirements"
    MACOSX_DEPLOYMENT_TARGET=14.0 uv pip compile "$ROOT/$requirements" \
      --python-version 3.13 --python-platform "$platform" \
      --constraint "$work/constraints.txt" --only-binary :all: --generate-hashes \
      --no-header --no-annotate --quiet
  } > "$work/out.txt"
  mv -f -- "$work/out.txt" "$ROOT/$out"
  echo "wrote $out"
}

mkdir -p -- "$ROOT/installer/locks"
compile requirements.txt aarch64-apple-darwin installer/locks/macos-arm64.txt \
  "Pinned dependencies of the full app for macOS 14 or newer on Apple Silicon, Python 3.13."
compile requirements-edge.txt x86_64-pc-windows-msvc installer/locks/windows-x64-edge.txt \
  "Pinned dependencies of the edge role for 64-bit Windows, Python 3.13."
