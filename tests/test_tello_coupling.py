"""Tello coupling ratchet: no new Tello-specific code outside the Tello backend (SEAM-9 (proposed)).

Scope: every ``*.py`` under ``flightrisk/`` and ``scripts/`` is scanned by AST, and every ``*.sh`` and
``*.ps1`` under ``scripts/`` by a token regex. ``mobile/``, ``ios/`` and ``tests/`` are not scanned: the
Android app drives a Tello directly, and tests migrate additively.

Allowed without a list: ``flightrisk/drone/tello*.py``, ``flightrisk/drone/registry.py`` and
``flightrisk/drone/backends.py``. ``PERMANENT_EXEMPTIONS`` names the files that stay coupled for a stated
reason. Everything else is counted per key ``(posix path, enclosing qualname or "", kind, token)`` and must
match ``tests/tello_coupling_baseline.py`` exactly, so line drift never breaks the test.

Finding kinds, one finding per AST node and always the most specific kind:

* ``import``: an ``Import``, an ``ImportFrom`` (relative forms resolved) or a constant-string
  ``importlib.import_module`` or ``__import__`` call naming ``flightrisk.drone.tello*`` or ``djitellopy``.
* ``compare``: a ``Compare`` operand that is the string ``tello``, ``tello_sdk_udp`` or ``tello_edu``
  (case-insensitive), a tuple, list or set literal containing one, or a name or attribute whose identifier
  contains ``tello``.
* ``name``: a load of a name or attribute whose identifier contains ``tello`` (case-insensitive).
* ``literal``: the string ``192.168.10.1`` or a string starting ``FLIGHTRISK_TELLO_``.
* ``model_default``: a Tello name string used directly as a parameter default, a keyword value or an
  assignment value, not inside a container.
* ``shell``: a token regex hit in a shell script.

Baseline file format (``tests/tello_coupling_baseline.py``, generated by chunk XCP-3, read lazily so this
file collects before it exists)::

    COUPLING_BASELINE: dict[str, dict[tuple[str, str, str, str], int]]  # section name -> {key: exact count}
    CLOSED_PHASES: tuple[str, ...]  # section names that must be empty

The ratchet is exact. A new key or a higher count fails with "new Tello coupling". A lower count or a key
that no longer occurs fails with "stale baseline entry, delete it". No key may sit in two sections, and
every section named in ``CLOSED_PHASES`` must be empty. Tests that read the baseline have "baseline" in
their name; ``scan_python_source``, ``scan_shell_text`` and ``scan_repository`` are public so the
baseline generator can reuse them.
"""

from __future__ import annotations

import ast
import importlib
import re
from collections import Counter
from functools import lru_cache
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parent.parent

Key = tuple[str, str, str, str]

PY_SCOPE_DIRS = ("flightrisk", "scripts")
SHELL_SCOPE_DIR = "scripts"
SHELL_SUFFIXES = (".sh", ".ps1")

TELLO_NAMES = frozenset({"tello", "tello_sdk_udp", "tello_edu"})
TELLO_ADDRESS = "192.168.10.1"
TELLO_ENV_PREFIX = "FLIGHTRISK_TELLO_"
TELLO_IDENTIFIER = re.compile(r"tello", re.IGNORECASE)
TELLO_MODULE = re.compile(r"^(flightrisk\.drone\.tello\w*|djitellopy)(\.|$)")
SHELL_TOKEN = re.compile(
    r"--source tello\b|--tello-[a-z-]+|FLIGHTRISK_TELLO_[A-Z_]+|192\.168\.10\.1\b|djitellopy|flightrisk\.drone\.tello"
)
IMPORT_CALLS = frozenset({"import_module", "__import__"})

#: Files that belong to the Tello backend or to the backend bootstrap; never counted.
ALLOWED_PATTERN = re.compile(r"^flightrisk/drone/(tello\w*|registry|backends)\.py$")

#: Files that stay coupled on purpose, with the reason.
PERMANENT_EXEMPTIONS: dict[str, str] = {
    "flightrisk/main.py": "XK-01: the single-process app imports the Tello controller directly and defaults its source to a Tello; kept by owner decision.",
    "flightrisk/drone/mavlink.py": "XK-02, XK-03: the legacy MAVLink controller is kept unchanged by owner decision.",
    "scripts/demo_edge.sh": "XK-04: the edge demo script is a Tello demo, pinned by tests/test_demo_smoke.py.",
    "scripts/demo_edge.ps1": "XK-04: the edge demo script is a Tello demo, pinned by tests/test_demo_smoke.py.",
    "scripts/demo_edge_pair.ps1": "XK-04: the edge demo script is a Tello demo, pinned by tests/test_demo_smoke.py.",
    "tests/test_demo_smoke.py": "XK-04: pins the demo scripts above; tests are not scanned.",
}


def _absolute_module(node: ast.ImportFrom, package: str | None) -> str | None:
    """The absolute module an ``ImportFrom`` names, resolving relative imports against ``package``."""
    if not node.level:
        return node.module
    if not package:
        return None
    parts = package.split(".")
    if node.level - 1 > len(parts):
        return None
    base = parts[: len(parts) - (node.level - 1)]
    if node.module:
        base.append(node.module)
    return ".".join(base) or None


def _package_of_rel(rel_path: str) -> str | None:
    """Dotted package containing the file at ``rel_path`` (``flightrisk.drone`` for flightrisk/drone/x.py)."""
    parts = PurePosixPath(rel_path).parent.parts
    return ".".join(parts) or None


def _tello_string(node: ast.AST) -> str | None:
    """The string value of ``node`` when it is a constant equal to a Tello model name, else ``None``."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str) and node.value.lower() in TELLO_NAMES:
        return node.value
    return None


def _identifier(node: ast.AST) -> str | None:
    """The identifier of a load of a name or attribute that contains ``tello``, else ``None``."""
    if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load) and TELLO_IDENTIFIER.search(node.id):
        return node.id
    if isinstance(node, ast.Attribute) and isinstance(node.ctx, ast.Load) and TELLO_IDENTIFIER.search(node.attr):
        return node.attr
    return None


def _import_call_target(node: ast.Call) -> str | None:
    """The constant module string of an ``import_module`` or ``__import__`` call naming a Tello module."""
    func = node.func
    callee = func.attr if isinstance(func, ast.Attribute) else func.id if isinstance(func, ast.Name) else None
    if callee not in IMPORT_CALLS or not node.args:
        return None
    first = node.args[0]
    if isinstance(first, ast.Constant) and isinstance(first.value, str) and TELLO_MODULE.match(first.value):
        return first.value
    return None


class _Scanner(ast.NodeVisitor):
    """Walks one module and counts findings per ``(path, qualname, kind, token)``."""

    def __init__(self, rel_path: str) -> None:
        self.rel_path = rel_path
        self.package = _package_of_rel(rel_path)
        self.scope: list[str] = []
        self.found: Counter[Key] = Counter()

    def _add(self, kind: str, token: str) -> None:
        self.found[(self.rel_path, ".".join(self.scope), kind, token)] += 1

    def _visit_value(self, node: ast.AST | None) -> None:
        """Visit a directly used value: a Tello name string is a ``model_default``, anything else recurses."""
        if node is None:
            return
        token = _tello_string(node)
        if token is not None:
            self._add("model_default", token)
        else:
            self.visit(node)

    def _visit_defaults(self, args: ast.arguments) -> None:
        for default in [*args.defaults, *args.kw_defaults]:
            self._visit_value(default)

    def _visit_function(self, node: ast.FunctionDef | ast.AsyncFunctionDef) -> None:
        for decorator in node.decorator_list:
            self.visit(decorator)
        self._visit_defaults(node.args)
        every_arg = [*node.args.posonlyargs, *node.args.args, *node.args.kwonlyargs]
        every_arg += [a for a in (node.args.vararg, node.args.kwarg) if a is not None]
        for arg in every_arg:
            if arg.annotation is not None:
                self.visit(arg.annotation)
        if node.returns is not None:
            self.visit(node.returns)
        self.scope.append(node.name)
        for statement in node.body:
            self.visit(statement)
        self.scope.pop()

    visit_FunctionDef = _visit_function
    visit_AsyncFunctionDef = _visit_function

    def visit_ClassDef(self, node: ast.ClassDef) -> None:
        for expression in [*node.decorator_list, *node.bases, *[k.value for k in node.keywords]]:
            self.visit(expression)
        self.scope.append(node.name)
        for statement in node.body:
            self.visit(statement)
        self.scope.pop()

    def visit_Lambda(self, node: ast.Lambda) -> None:
        self._visit_defaults(node.args)
        self.visit(node.body)

    def visit_Import(self, node: ast.Import) -> None:
        for alias in node.names:
            if TELLO_MODULE.match(alias.name):
                self._add("import", alias.name)

    def visit_ImportFrom(self, node: ast.ImportFrom) -> None:
        module = _absolute_module(node, self.package)
        if not module:
            return
        if TELLO_MODULE.match(module):
            self._add("import", module)
            return
        for alias in node.names:
            if TELLO_MODULE.match(f"{module}.{alias.name}"):
                self._add("import", f"{module}.{alias.name}")

    def visit_Call(self, node: ast.Call) -> None:
        target = _import_call_target(node)
        if target is not None:
            self._add("import", target)
        self.visit(node.func)
        for index, argument in enumerate(node.args):
            if index == 0 and target is not None:
                continue
            self.visit(argument)
        for keyword in node.keywords:
            self._visit_value(keyword.value)

    def visit_Assign(self, node: ast.Assign) -> None:
        for target in node.targets:
            self.visit(target)
        self._visit_value(node.value)

    def visit_AnnAssign(self, node: ast.AnnAssign) -> None:
        self.visit(node.target)
        self.visit(node.annotation)
        self._visit_value(node.value)

    def visit_Compare(self, node: ast.Compare) -> None:
        for operand in [node.left, *node.comparators]:
            self._visit_operand(operand)

    def _visit_operand(self, operand: ast.AST) -> None:
        token = _tello_string(operand)
        if token is not None:
            self._add("compare", token)
        elif isinstance(operand, (ast.Tuple, ast.List, ast.Set)):
            for element in operand.elts:
                element_token = _tello_string(element)
                if element_token is not None:
                    self._add("compare", element_token)
                else:
                    self.visit(element)
        else:
            identifier = _identifier(operand)
            if identifier is None:
                self.visit(operand)
                return
            self._add("compare", identifier)
            if isinstance(operand, ast.Attribute):
                self.visit(operand.value)

    def visit_Name(self, node: ast.Name) -> None:
        identifier = _identifier(node)
        if identifier is not None:
            self._add("name", identifier)

    def visit_Attribute(self, node: ast.Attribute) -> None:
        identifier = _identifier(node)
        if identifier is not None:
            self._add("name", identifier)
        self.visit(node.value)

    def visit_Constant(self, node: ast.Constant) -> None:
        value = node.value
        if isinstance(value, str) and (value == TELLO_ADDRESS or value.startswith(TELLO_ENV_PREFIX)):
            self._add("literal", value)


def scan_python_source(text: str, rel_path: str) -> Counter[Key]:
    """Count the findings in one Python module; ``rel_path`` is its posix path from the repository root."""
    scanner = _Scanner(rel_path)
    scanner.visit(ast.parse(text, filename=rel_path))
    return scanner.found


def scan_shell_text(text: str, rel_path: str) -> Counter[Key]:
    """Count the token regex hits in one shell script; the qualname is always empty."""
    found: Counter[Key] = Counter()
    for match in SHELL_TOKEN.finditer(text):
        found[(rel_path, "", "shell", match.group(0))] += 1
    return found


def _scoped_files(root: Path) -> list[Path]:
    paths: list[Path] = []
    for directory in PY_SCOPE_DIRS:
        paths.extend(root.joinpath(directory).rglob("*.py"))
    for suffix in SHELL_SUFFIXES:
        paths.extend(root.joinpath(SHELL_SCOPE_DIR).rglob(f"*{suffix}"))
    return sorted({p for p in paths if "__pycache__" not in p.parts})


def scan_repository(root: Path) -> Counter[Key]:
    """Count every finding under ``root``, applying the scope, the allowed files and the exemptions."""
    found: Counter[Key] = Counter()
    for path in _scoped_files(root):
        rel = path.relative_to(root).as_posix()
        if ALLOWED_PATTERN.match(rel) or rel in PERMANENT_EXEMPTIONS:
            continue
        text = path.read_text(encoding="utf-8")
        found.update(scan_python_source(text, rel) if path.suffix == ".py" else scan_shell_text(text, rel))
    return found


@lru_cache(maxsize=1)
def _repository_scan() -> Counter[Key]:
    return scan_repository(ROOT)


def _format_keys(rows: list[tuple[Key, int, int]]) -> str:
    return "\n".join(f"  {key} found={found} baseline={allowed}" for key, found, allowed in rows)


def ratchet_problems(
    found: Counter[Key],
    baseline: dict[str, dict[Key, int]],
    closed_phases: tuple[str, ...] = (),
) -> list[str]:
    """Every way ``found`` fails the exact ratchet against ``baseline``; an empty list means it passes."""
    problems: list[str] = []
    owners: dict[Key, list[str]] = {}
    expected: Counter[Key] = Counter()
    for section, keys in baseline.items():
        for key, count in keys.items():
            owners.setdefault(key, []).append(section)
            expected[key] += count
    for key, sections in sorted(owners.items()):
        if len(sections) > 1:
            problems.append(f"key sits in two sections {sorted(sections)}: {key}")
    for section in closed_phases:
        if baseline.get(section):
            problems.append(f"closed phase {section!r} must be empty but holds {len(baseline[section])} keys")
    new = [(k, found[k], expected.get(k, 0)) for k in sorted(found) if found[k] > expected.get(k, 0)]
    if new:
        problems.append(f"new Tello coupling, route it through the registry or the backend:\n{_format_keys(new)}")
    stale = [(k, found.get(k, 0), expected[k]) for k in sorted(expected) if found.get(k, 0) < expected[k]]
    if stale:
        problems.append(f"stale baseline entry, delete it:\n{_format_keys(stale)}")
    return problems


def _load_baseline() -> tuple[dict[str, dict[Key, int]], tuple[str, ...]]:
    module = importlib.import_module("tests.tello_coupling_baseline")
    return module.COUPLING_BASELINE, tuple(module.CLOSED_PHASES)


# Tests that read the baseline file. They fail until chunk XCP-3 generates it.


def test_baseline_matches_scan():
    baseline, closed = _load_baseline()
    assert ratchet_problems(_repository_scan(), baseline, closed) == []


def test_baseline_format():
    baseline, closed = _load_baseline()
    for section, keys in baseline.items():
        for key, count in keys.items():
            assert isinstance(key, tuple) and len(key) == 4 and all(isinstance(p, str) for p in key), (section, key)
            assert isinstance(count, int) and count > 0, (section, key, count)
    assert set(closed) <= set(baseline), sorted(set(closed) - set(baseline))


