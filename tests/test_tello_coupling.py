# Mutation-style self-tests on temporary repositories.


def _baseline_of(found: Counter[Key]) -> dict[str, dict[Key, int]]:
    """A baseline that accepts ``found``: permanent-exempt files in ``permanent``, the rest in ``A3``."""
    baseline: dict[str, dict[Key, int]] = {PERMANENT_SECTION: {}, "A3": {}}
    for key, count in found.items():
        baseline[PERMANENT_SECTION if key[0] in PERMANENT_EXEMPTIONS else "A3"][key] = count
    return baseline


def test_mutation_grow_is_rejected_by_the_format_check(tmp_path):
    _scan(tmp_path, "flightrisk/recorder.py", "x = 1\n")
    before = scan_repository(tmp_path)
    baseline = _baseline_of(before)
    assert ratchet_problems(before, baseline) == []
    grown = _scan(tmp_path, "flightrisk/recorder.py", "x = 1\nimport djitellopy\n")
    assert any("new Tello coupling" in p for p in ratchet_problems(grown, baseline))
    cheating = {**baseline, "A9": dict(grown)}
    assert ratchet_problems(grown, cheating) == []
    assert baseline_format_problems(cheating, ()) != []
    assert any("not allowed" in p for p in baseline_format_problems({"grown": dict(grown)}, ()))


