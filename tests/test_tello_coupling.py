"""Tello coupling ratchet: no new Tello-specific code outside the Tello backend (SEAM-9 (proposed)).

Scope: every ``*.py`` under ``flightrisk/`` and ``scripts/`` is scanned by AST, and every ``*.sh`` and
``*.ps1`` under ``scripts/`` by a token regex. ``mobile/``, ``ios/`` and ``tests/`` are not scanned: the
Android app drives a Tello directly, and tests migrate additively.

Allowed without a list: exactly the four files in ``ALLOWED_FILES`` (``flightrisk/drone/tello.py``,
``tello_bound.py``, ``registry.py`` and ``backends.py``). Any other file, including a new
``flightrisk/drone/tello*.py``, is scanned. ``PERMANENT_EXEMPTIONS`` names the files that stay coupled for a
stated reason; they are scanned like any other file, and their findings are compared with the pinned
``"permanent"`` baseline section. Everything else is counted per key
``(posix path, enclosing qualname or "", kind, token)`` and must match ``tests/tello_coupling_baseline.py``
exactly, so line drift never breaks the test.

Finding kinds, one finding per AST node and always the most specific kind:

* ``import``: an ``Import``, an ``ImportFrom`` (relative forms resolved), an imported name or alias that
  contains ``tello``, a ``import_module`` or ``__import__`` call naming ``flightrisk.drone.tello*`` or
  ``djitellopy`` (constant name, ``name`` keyword, relative name resolved against the ``package`` argument,
  or a ``fromlist`` entry), or any other string constant that is such a module path.
* ``compare``: a ``Compare`` operand that is the string ``tello``, ``tello_sdk_udp`` or ``tello_edu``
  (case-insensitive), a tuple, list or set literal containing one, or a name or attribute whose identifier
  contains ``tello``.
* ``name``: a load of a name or attribute whose identifier contains ``tello`` (case-insensitive), or a
  ``getattr``, ``hasattr``, ``setattr`` or ``delattr`` attribute-name string containing ``tello``.
* ``literal``: the string ``192.168.10.1``, a string starting ``FLIGHTRISK_TELLO_``, a Tello model name
  string in any other position (call argument, ``or`` or conditional default, ``return`` value, container
  element, dict value, ``match`` pattern, augmented assignment and so on), or a ``startswith`` or
  ``endswith`` argument that starts with ``tello``. Docstrings (bare string statements) and dict keys are
  skipped.
* ``model_default``: a Tello name string used directly as a parameter default, a keyword value or an
  assignment value, not inside a container.
* ``shell``: a token regex hit in a shell script (``--drone tello`` and ``--source tello`` in any spacing,
  ``=`` or quoting, ``--tello-*``, ``FLIGHTRISK_TELLO_*``, ``192.168.10.1``, ``djitellopy``). PowerShell
  scripts match case-insensitively and the token is normalised.

Baseline file format (``tests/tello_coupling_baseline.py``, generated by chunk XCP-3, read lazily so this
file collects before it exists)::

    COUPLING_BASELINE: dict[str, dict[tuple[str, str, str, str], int]]  # section name -> {key: exact count}
    CLOSED_PHASES: tuple[str, ...]  # section names that must be empty

Section names are pinned by ``ALLOWED_SECTIONS``; ``baseline_format_problems`` rejects any other name. The
section ``"permanent"`` holds exactly the findings in files named by ``PERMANENT_EXEMPTIONS``, and nothing
else may be in it. It is never asked to shrink and is never in ``CLOSED_PHASES``.

The ratchet is exact. A new key or a higher count fails with "new Tello coupling". A lower count or a key
that no longer occurs fails with "stale baseline entry, delete it". No key may sit in two sections, and
every section named in ``CLOSED_PHASES`` must be empty. Tests that read the baseline have "baseline" in
their name; ``scan_python_source``, ``scan_shell_text`` and ``scan_repository`` are public so the
baseline generator can reuse them.
"""

