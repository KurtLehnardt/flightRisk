def _scan(tmp_path: Path, rel: str, text: str) -> Counter[Key]:
    path = tmp_path / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return scan_repository(tmp_path)


