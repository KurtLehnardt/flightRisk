def test_param_value_frames_state_their_integer_encoding():
    for frame in (f for f in FRAMES["frames"] if f["msg"] == "PARAM_VALUE"):
        raw = bytes.fromhex(frame["float_bits"]["param_value"])
        if frame["value"]["encoding"] == "bytewise":
            assert struct.unpack(">i", raw)[0] == frame["value"]["int"]
        else:
            assert struct.unpack(">f", raw)[0] == frame["value"]["number"]
    negative = next(f for f in FRAMES["frames"] if f["name"] == "param_value_px4_int32_negative_bytewise")
    assert negative["float_bits"]["param_value"] == "ffffffff" and negative["fields"]["param_value"] == "NaN"


