def _expected_items(tr):
    rules_home = tr["autopilot"] == "ardupilot"
    args = tr["op"]["args"]
    items = ([{"kind": "home", **args["home"]}] if rules_home else []) + args["items"]
    out = []
    for seq, item in enumerate(items):
        f = {"target_system": 1, "target_component": 1, "seq": seq, "current": 0, "autocontinue": 1, "mission_type": 0}
        if item["kind"] == "home":
            f.update(frame=0, command=16, x=item["lat_e7"], y=item["lon_e7"], z=0.0)
        elif item["kind"] in ("takeoff", "waypoint"):
            f.update(frame=3, command=22 if item["kind"] == "takeoff" else 16, param4="NaN", x=item["lat_e7"],
                     y=item["lon_e7"], z=item["alt_cm"] / 100)
        elif item["kind"] == "speed":
            f.update(frame=2, command=178, param1=1.0, param2=item["cm_s"] / 100, param3=-1.0)
        else:
            f.update(frame=2, command=20)
        out.append(f)
    return out


