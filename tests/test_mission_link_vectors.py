# An independent MAVLink 2 parser and decoder built from the published layouts
# ------------------------------------------------------------------------------------------------------

_PACK = {"uint8_t": "B", "int8_t": "b", "uint16_t": "H", "int16_t": "h", "uint32_t": "I", "int32_t": "i",
         "uint64_t": "Q", "int64_t": "q", "float": "f", "double": "d", "char": "s"}
_SIZE = {"uint8_t": 1, "int8_t": 1, "char": 1, "uint16_t": 2, "int16_t": 2, "uint32_t": 4, "int32_t": 4,
         "float": 4, "uint64_t": 8, "int64_t": 8, "double": 8}
_BY_ID = {layout["id"]: (name, layout) for name, layout in LAYOUTS.items()}


def crc_x25(data: bytes) -> int:
    crc = 0xFFFF
    for byte in data:
        tmp = byte ^ (crc & 0xFF)
        tmp = (tmp ^ (tmp << 4)) & 0xFF
        crc = ((crc >> 8) ^ (tmp << 8) ^ (tmp << 3) ^ (tmp >> 4)) & 0xFFFF
    return crc


def parse(buf: bytes) -> list[tuple[str, bytes]]:
    """Frames a strict v1 decoder accepts: MAVLink 2, no incompat flags, known id, valid checksum. After any
    frame it cannot accept it resumes at the next byte."""
    out, i = [], 0
    while i < len(buf):
        if buf[i] != 0xFD:
            i += 1
            continue
        if i + 12 > len(buf):
            break
        n, incompat = buf[i + 1], buf[i + 2]
        end = i + 12 + n
        if end > len(buf):
            break
        msgid = int.from_bytes(buf[i + 7:i + 10], "little")
        known = _BY_ID.get(msgid)
        if incompat or known is None:
            i += 1
            continue
        name, layout = known
        crc = int.from_bytes(buf[end - 2:end], "little")
        if crc != crc_x25(buf[i + 1:end - 2] + bytes([layout["crc_extra"]])):
            i += 1
            continue
        out.append((name, buf[i:end]))
        i = end
    return out


def decode(name: str, frame: bytes) -> tuple[dict, dict]:
    """Decode one frame to (fields, float bits). Missing payload bytes are zero; extra bytes are ignored."""
    layout = LAYOUTS[name]
    payload = frame[10:10 + frame[1]]
    payload = payload[:layout["max_len"]] + bytes(max(0, layout["max_len"] - len(payload)))
    fields, bits = {}, {}
    for field in layout["fields"]:
        ftype, count, offset = field["type"], field["array"], field["offset"]
        if ftype == "char":
            raw = payload[offset:offset + (count or 1)]
            fields[field["name"]] = raw.split(b"\x00", 1)[0].decode("ascii")
            continue
        fmt = "<" + (str(count) if count else "") + _PACK[ftype]
        values = list(struct.unpack_from(fmt, payload, offset))
        if ftype == "float":
            raw = [payload[offset + 4 * k:offset + 4 * k + 4][::-1].hex() for k in range(count or 1)]
            bits[field["name"]] = raw if count else raw[0]
            values = ["NaN" if math.isnan(v) else v for v in values]
        fields[field["name"]] = values if count else values[0]
    return fields, bits


def test_layouts_agree_with_pymavlink(pymavlink_ok):
    from pymavlink.dialects.v20 import common

    assert set(LAYOUTS) == set(FRAMES["subset"])
    assert {"MISSION_REQUEST", "PARAM_ERROR"} == set(FRAMES["added_to_plan_subset"])
    for name, layout in LAYOUTS.items():
        cls = getattr(common, "MAVLink_%s_message" % name.lower())
        assert (cls.id, cls.crc_extra) == (layout["id"], layout["crc_extra"]), name
        assert [f["name"] for f in layout["fields"]] == list(cls.ordered_fieldnames), name
        sizes = [_SIZE[f["type"]] * (f["array"] or 1) for f in layout["fields"]]
        assert sum(sizes) == layout["max_len"], name
        base = [s for s, f in zip(sizes, layout["fields"]) if not f["extension"]]
        assert sum(base) == layout["min_len"], name
        offsets = [0]
        for s in sizes[:-1]:
            offsets.append(offsets[-1] + s)
        assert offsets == [f["offset"] for f in layout["fields"]], name


