@pytest.mark.parametrize("frame", FRAMES["frames"], ids=lambda f: f["name"])
def test_golden_frame_checks_out_independently(frame):
    data = bytes.fromhex(frame["hex"])
    assert data[0] == 0xFD and data[2] == 0 and data[3] == 0
    assert (data[1], data[4], data[5], data[6]) == (frame["payload_len"], frame["seq"], frame["sysid"], frame["compid"])
    assert int.from_bytes(data[7:10], "little") == frame["msgid"] == LAYOUTS[frame["msg"]]["id"]
    assert len(data) == 12 + data[1]
    payload = data[10:10 + data[1]]
    assert data[1] >= 1 and (data[1] == 1 or payload[-1] != 0), "MAVLink 2 truncates trailing zero bytes"
    assert frame["truncated"] == (data[1] < LAYOUTS[frame["msg"]]["max_len"])
    assert parse(data) == [(frame["msg"], data)]
    fields, bits = decode(frame["msg"], data)
    assert bits == frame["float_bits"]
    for key, value in frame["fields"].items():
        got = fields[key]
        if isinstance(value, float):
            assert struct.pack("<f", got) == struct.pack("<f", value), key
        else:
            assert got == value, key


