def _phone(tr, msg):
    return [s for s in tr["steps"] if s.get("from") == "phone" and s["msg"] == msg]


@pytest.mark.parametrize("tr", ALL, ids=lambda t: t["id"])
def test_retries_follow_the_timing_rules(tr):
    timing = TRANSCRIPTS["timing"]
    commands = _phone(tr, "COMMAND_LONG")
    run = []
    for step in commands + [None]:
        key = None if step is None else (step["fields"]["command"], step["fields"].get("param1", 0.0),
                                         step["fields"].get("param2", 0.0), step["fields"].get("param3", 0.0))
        if run and (step is None or key != run[-1][0] or step["fields"].get("confirmation", 0) == 0):
            tries = [s for _, s in run]
            assert len(tries) <= timing["tries"]
            for k, s in enumerate(tries):
                assert s["fields"].get("confirmation", 0) == k
                if k:
                    assert s["t"] - tries[k - 1]["t"] == timing["retry_ms"]
            run = []
        if step is not None:
            run.append((key, step))
    for msg, key in (("PARAM_REQUEST_READ", "param_id"), ("MISSION_COUNT", "count")):
        steps = _phone(tr, msg)
        for value in {s["fields"][key] for s in steps}:
            tries = [s for s in steps if s["fields"][key] == value]
            assert len(tries) <= timing["tries"]
            assert all(b["t"] - a["t"] == timing["retry_ms"] for a, b in zip(tries, tries[1:]))
    if tr["result"] and tr["result"]["outcome"] == "timeout" and tr["op"]["name"] != "upload_mission":
        sent = [s for s in tr["steps"] if s.get("from") == "phone"]
        assert tr["result"]["t"] - sent[-1]["t"] == timing["retry_ms"]


