# RTP: an independent depacketizer
# ------------------------------------------------------------------------------------------------------


class Depacketizer:
    def __init__(self):
        self.counters = {c: 0 for c in ("stap_a_dropped", "fu_a_dropped", "unsupported_dropped", "invalid_dropped")}
        self.out = []
        self.fu = None  # (timestamp, last seq, header byte, body, packet count)

    def _abandon(self):
        if self.fu:
            self.counters["fu_a_dropped"] += self.fu[4]
            self.fu = None

    def feed(self, pkt: bytes):
        if len(pkt) < 12 or pkt[0] >> 6 != 2:
            self.counters["invalid_dropped"] += 1
            return
        off = 12 + 4 * (pkt[0] & 0x0F)
        if pkt[0] & 0x10:
            if len(pkt) < off + 4:
                self.counters["invalid_dropped"] += 1
                return
            off += 4 + 4 * int.from_bytes(pkt[off + 2:off + 4], "big")
        end = len(pkt)
        if pkt[0] & 0x20:
            end -= pkt[-1]
        if end <= off:
            self.counters["invalid_dropped"] += 1
            return
        marker = bool(pkt[1] & 0x80)
        seq = int.from_bytes(pkt[2:4], "big")
        ts = int.from_bytes(pkt[4:8], "big")
        payload = pkt[off:end]
        kind = payload[0] & 0x1F
        if kind == 28:
            if len(payload) < 2:
                self.counters["invalid_dropped"] += 1
                return
            start, stop = payload[1] & 0x80, payload[1] & 0x40
            if start:
                self._abandon()
                header = (payload[0] & 0xE0) | (payload[1] & 0x1F)
                self.fu = (ts, seq, header, bytearray(payload[2:]), 1)
            elif self.fu and self.fu[0] == ts and (self.fu[1] + 1) & 0xFFFF == seq:
                self.fu = (ts, seq, self.fu[2], self.fu[3] + payload[2:], self.fu[4] + 1)
            else:
                self._abandon()
                self.counters["fu_a_dropped"] += 1
                return
            if stop:
                self.out.append({"ts": ts, "au_end": marker, "nal": (bytes([self.fu[2]]) + bytes(self.fu[3])).hex()})
                self.fu = None
            return
        self._abandon()
        if kind == 24:
            self.counters["stap_a_dropped"] += 1
        elif 1 <= kind <= 23:
            self.out.append({"ts": ts, "au_end": marker, "nal": payload.hex()})
        else:
            self.counters["unsupported_dropped"] += 1


@pytest.mark.parametrize("case", RTP["cases"], ids=lambda c: c["name"])
def test_rtp_case_depacketizes_to_the_expected_nal_units(case):
    dep = Depacketizer()
    for packet in case["packets"]:
        dep.feed(bytes.fromhex(packet["hex"]))
    dep._abandon()
    assert dep.out == case["nals"]
    assert dep.counters == case["counters"]


def test_rtp_cases_cover_every_rule():
    names = {c["name"] for c in RTP["cases"]}
    assert {"single_nal_units", "fu_a", "stap_a_dropped", "fu_a_gap", "fu_a_without_start", "fu_a_timestamp_change",
            "fu_a_interrupted", "sequence_wrap", "header_variants", "dropped_packets"} <= names
    totals = {k: sum(c["counters"][k] for c in RTP["cases"]) for k in RTP["cases"][0]["counters"]}
    assert all(totals.values()), totals


