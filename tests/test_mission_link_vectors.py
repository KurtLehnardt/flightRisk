def test_mode_table_names_and_roles():
    roles = {"mission", "takeoff", "hold", "return", "land", "other"}
    for autopilot, rows in TRANSCRIPTS["modes"].items():
        assert len({r["custom_mode"] for r in rows}) == len(rows)
        assert {r["role"] for r in rows} <= roles
        for row in rows:
            if autopilot == "px4":
                main, sub = (row["custom_mode"] >> 16) & 0xFF, (row["custom_mode"] >> 24) & 0xFF
                assert row["custom_mode"] & 0xFFFF == 0 and row["name"].split(".")[0] in (
                    "MANUAL", "ALTCTL", "POSCTL", "AUTO", "ACRO", "OFFBOARD", "STABILIZED"), row
                assert (sub != 0) == ("." in row["name"]) and main
    by_role = {(a, r["role"]): r["custom_mode"] for a, rows in TRANSCRIPTS["modes"].items() for r in rows
               if r["role"] in ("hold", "mission", "land") and r["name"] not in ("AUTO.PRECLAND",)}
    for autopilot, roles_map in TRANSCRIPTS["set_mode"].items():
        for role, (base, p2, p3) in roles_map.items():
            assert base == 1
            custom = int(p2) if autopilot == "ardupilot" else (int(p2) << 16) | (int(p3) << 24)
            assert by_role[(autopilot, role)] == custom, (autopilot, role)
