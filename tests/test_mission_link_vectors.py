@pytest.mark.parametrize("tr", ALL, ids=lambda t: t["id"])
def test_transcript_is_well_formed_and_cited(tr):
    assert tr["op"]["name"] in OPS
    assert tr["encodes"].strip() and tr["title"].strip()
    keys = [c.split(" ", 1)[0] for c in tr["cites"]]
    assert keys and set(keys) <= set(TRANSCRIPTS["sources"])
    if tr["autopilot"] in OWN_SOURCES:
        assert OWN_SOURCES[tr["autopilot"]] & set(keys), "cite the autopilot's own source"
    last = -1
    for step in tr["steps"]:
        assert step["t"] >= last
        last = step["t"]
        if "msg" in step:
            assert step["msg"] in LAYOUTS and step["from"] in ("phone", "vehicle")
            names = {f["name"] for f in LAYOUTS[step["msg"]]["fields"]}
            assert set(step["fields"]) <= names
        else:
            assert step["query"] in ("snapshot", "statustext")
            if step["query"] == "snapshot":
                assert set(step["expect"]) <= SNAPSHOT_KEYS
    result = tr["result"]
    if tr["op"]["name"] == "observe":
        assert result is None
    elif result is not None:
        assert result["outcome"] in ("ok", "refused", "timeout") and result["t"] <= tr["end_ms"]
    assert last <= tr["end_ms"]
    if tr["heartbeats"] == "ignore":
        assert not [s for s in tr["steps"] if s.get("from") == "phone" and s["msg"] == "HEARTBEAT"]


